class Profile {
  String name;
  String nim;
  String major;
  String classRoom;
  String bio;
  String email;
  String phone;
  String github;
  String imagePath;

  Profile({
    required this.name,
    required this.nim,
    required this.major,
    required this.classRoom,
    required this.bio,
    required this.email,
    required this.phone,
    required this.github,
    required this.imagePath,
  });
}